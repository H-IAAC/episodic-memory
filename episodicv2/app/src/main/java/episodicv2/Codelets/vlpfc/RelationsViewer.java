    private void loadImages() {
        try {

            for (int i = 1; i <= MAX_FEATURES; i++) {

                BufferedImage features = ImageIO.read(new File(PATH + "" + i + ".jpg"));

                classFeatures.put(i, features);

            }

        } catch (IOException ex) {
            ex.printStackTrace();
        }
    }

    public void addRelations(ConcurrentHashMap<Integer, ObjectRelations> relMap) {
        try {

            relationsMap = new ConcurrentHashMap<Integer, ObjectRelations>();
            relationsMap.putAll(relMap);

            objectListModel.clear();
            relationsListModel.clear();

            Iterator<Map.Entry<Integer, ObjectRelations>> it = relationsMap.entrySet().iterator();

            while (it.hasNext()) {
                Map.Entry<Integer, ObjectRelations> item = it.next();

                objectListModel.addElement(item.getKey());

                for (Integer oc : item.getValue().getRelations()) {
                    relationsListModel.addElement(oc);
                }

            }

            /*
            for (Integer objectId : relationsMap.keySet()) {

                objectListModel.addElement(objectId);

                for (Integer oc : relationsMap.get(objectId).getRelations()) {
                    relationsListModel.addElement(oc);
                }

            }*/
        } catch (Exception e) {
            e.printStackTrace();
        }

    }

