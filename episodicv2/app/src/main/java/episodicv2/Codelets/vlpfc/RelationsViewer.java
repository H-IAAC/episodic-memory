    private void objectListMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_objectListMouseClicked

        try {
            
            int objectId = objectList.getSelectedValue();

            relationsListModel.clear();

            for (Integer oc : relationsMap.get(objectId).getRelations()) {
                relationsListModel.addElement(oc);
            }

            positiveAffectComponent.setPercent(relationsMap.get(objectId).getPositiveAffect());
            negativeAffectComponent.setPercent(relationsMap.get(objectId).getNegativeAffect());
            
            System.out.println(relationsMap.get(objectId).getPositiveAffect());
            
        } catch (Exception e) {
            System.out.println("Click en ejecución: ");
        }


    }//GEN-LAST:event_objectListMouseClicked

    private void relationsListMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_relationsListMouseClicked

        int objectClass1 = objectList.getSelectedValue();
        int objectClass2 = relationsList.getSelectedValue();

        BufferedImage img1 = classFeatures.get(objectClass1);
        BufferedImage img2 = classFeatures.get(objectClass2);

        object1Img.setImage(img1);
        object2Img.setImage(img2);

    }//GEN-LAST:event_relationsListMouseClicked

