    private ScenesViewer() {
        initComponents();

        memoryPanel = new MemoryPanel(Configuration.GRID_COLUMNS_X, Configuration.GRID_ROWS_Y);
        positiveAffectComponent = new PercentLevelComponent(0.0, true);
        negativeAffectComponent = new PercentLevelComponent(0.0, false);

        scenes = new ArrayList<>();
        relations = new ConcurrentHashMap<>();

        scenesListModel = new DefaultListModel();
        relationsListModel = new DefaultListModel();

        scenesList.setModel(scenesListModel);
        relationsList.setModel(relationsListModel);

        scenesPanel.add(memoryPanel);

        positiveAffectContainer.add(positiveAffectComponent);
        negativeAffectContainer.add(negativeAffectComponent);

        setTitle("Episodic Working Memory");
    }

    public void setItems(ArrayList<Scene> scenes) {

        if (scenes.size() > 0) {
            this.scenes = scenes;

            scenesListModel.clear();

            for (Scene scene : scenes) {
                scenesListModel.addElement(scene);
            }

        }

    }

    public void setPerceivedScene(Scene scene) {

        sceneData.setText(scene.getPattern());

        memoryPanel.setImage(T2DString.decodeMatrix(scene.getPattern(),
                Configuration.GRID_COLUMNS_X,
                Configuration.GRID_ROWS_Y));

        positiveAffectComponent.setPercent(scene.getPositiveAffect());
        negativeAffectComponent.setPercent(scene.getNegativeAffect());
        
        
    }

    public void setRelations(int sceneId, ArrayList<SceneRelation> addRelations) {

        if (sceneId != 0) {
            System.out.println(addRelations.get(0).getScene2Id() + "-");
            relations.put(sceneId, addRelations);
        }
    }

    public void setRelations(ConcurrentHashMap<Integer, ArrayList<SceneRelation>> relations) {

        this.relations = relations;
    }

    public void setImage(ArrayList<Integer>[][] imgM) {
        memoryPanel.setImage(imgM);
    }

