    private void scenesListMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_scenesListMouseClicked

        try {
            Scene scene = scenesList.getSelectedValue();
            sceneData.setText(scene.toString());

            memoryPanel.setImage(T2DString.decodeMatrix(scene.getPattern(),
                    Configuration.GRID_COLUMNS_X,
                    Configuration.GRID_ROWS_Y));

            positiveAffectComponent.setPercent(scene.getPositiveAffect());
            negativeAffectComponent.setPercent(scene.getNegativeAffect());

            relationsListModel.clear();

            for (SceneRelation sr : relations.get(scene.getId())) {
                relationsListModel.addElement(sr.toString());
            }
        } catch (Exception e) {
            //e.printStackTrace();
            System.out.println("SEGURO LE DISTE CLICK EN EJECUCION");
        }


    }//GEN-LAST:event_scenesListMouseClicked

